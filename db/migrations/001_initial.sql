-- Initial Neon/PostgreSQL schema for Credit Card Manager.
-- Amounts are integer paise. Local transaction/payment times are stored as timestamp
-- without time zone to preserve the current app's Asia/Kolkata wall-clock semantics.

CREATE TABLE IF NOT EXISTS schema_migrations (
  version TEXT PRIMARY KEY,
  applied_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS app_user (
  id BIGINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS remember_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_remember_tokens_expiry ON remember_tokens(expires_at);

CREATE TABLE IF NOT EXISTS app_settings (
  setting_key TEXT PRIMARY KEY,
  setting_value TEXT NOT NULL,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS credit_cards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  bank_name TEXT NOT NULL,
  last4 TEXT NOT NULL DEFAULT '',
  credit_limit_minor BIGINT CHECK (credit_limit_minor IS NULL OR credit_limit_minor >= 0),
  billing_day SMALLINT NOT NULL DEFAULT 5 CHECK (billing_day BETWEEN 1 AND 31),
  billing_rule TEXT NOT NULL DEFAULT 'end' CHECK (billing_rule IN ('end','start')),
  due_days INTEGER NOT NULL DEFAULT 20 CHECK (due_days >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS upi_apps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_upi_apps_name_case_insensitive ON upi_apps (lower(name));

CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id BIGINT NOT NULL REFERENCES credit_cards(id) ON DELETE RESTRICT,
  particular TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT '',
  tags TEXT NOT NULL DEFAULT '',
  amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
  txn_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  settlement_date DATE NOT NULL,
  payment_method TEXT NOT NULL CHECK (payment_method IN ('swipe','online','upi')),
  upi_app_id BIGINT REFERENCES upi_apps(id) ON DELETE SET NULL,
  upi_app_name TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  attachment_key TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_transactions_card_settlement ON transactions(card_id, settlement_date);
CREATE INDEX IF NOT EXISTS idx_transactions_txn_at ON transactions(txn_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_transactions_card_method ON transactions(card_id, payment_method);
CREATE INDEX IF NOT EXISTS idx_transactions_upi_app ON transactions(upi_app_id);

CREATE TABLE IF NOT EXISTS statements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id BIGINT NOT NULL REFERENCES credit_cards(id) ON DELETE RESTRICT,
  cycle_start DATE NOT NULL,
  cycle_end DATE NOT NULL,
  statement_date DATE NOT NULL,
  due_date DATE NOT NULL,
  amount_minor BIGINT NOT NULL DEFAULT 0 CHECK (amount_minor >= 0),
  bank_amount_minor BIGINT CHECK (bank_amount_minor IS NULL OR bank_amount_minor >= 0),
  confirmed_at TIMESTAMP WITHOUT TIME ZONE,
  is_locked BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT statements_cycle_order CHECK (cycle_start <= cycle_end),
  CONSTRAINT uq_statements_card_cycle UNIQUE(card_id, cycle_start, cycle_end)
);
CREATE INDEX IF NOT EXISTS idx_statements_card_due ON statements(card_id, due_date DESC);

CREATE TABLE IF NOT EXISTS bill_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id BIGINT NOT NULL REFERENCES credit_cards(id) ON DELETE RESTRICT,
  amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
  paid_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  reference TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_bill_payments_card_paid_at ON bill_payments(card_id, paid_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS payment_allocations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id BIGINT NOT NULL REFERENCES bill_payments(id) ON DELETE CASCADE,
  statement_id BIGINT NOT NULL REFERENCES statements(id) ON DELETE RESTRICT,
  amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
  CONSTRAINT uq_payment_statement UNIQUE(payment_id, statement_id)
);
CREATE INDEX IF NOT EXISTS idx_payment_allocations_statement ON payment_allocations(statement_id);
CREATE INDEX IF NOT EXISTS idx_payment_allocations_payment ON payment_allocations(payment_id);

